import { writeFile } from "node:fs/promises"
import { resolve } from "node:path"

/**
 * Vendors the Tock icon shapes the animated `TockIcon` uses (channel duet icons, follow-up glass icons) into
 * ../vendor/tock-icons/data.js, with their built-in colour and motion picks. The engine itself is vendored as is.
 * `bun scripts/tock-vendor.ts <tock-icons>/tock-icons-data.js`
 */
export const tockNames = [
  // Channels (lib/glyph.ts)
  "code", "calendar-check", "chart-line-up", "hash", "globe", "broom", "currency-dollar", "airplane-tilt", "palette",
  // Follow-ups (chat/followup-icons.ts)
  "sparkle", "git-pull-request", "flask", "note-pencil", "cloud-rain", "calendar-blank", "magnifying-glass", "bug",
  "rocket-launch", "lightbulb", "chat-circle", "list-checks", "file-text", "image", "pencil-simple", "check-circle",
  "lightning", "arrow-clockwise", "play", "map-trifold", "suitcase-rolling", "chart-bar", "envelope-simple", "lock-simple",
  "trash", "wrench", "question", "book-open", "terminal-window", "shopping-cart", "heart", "star", "clock", "users",
] as const

const from = process.argv[2]
if (!from) throw new Error("usage: bun scripts/tock-vendor.ts <tock-icons-data.js>")
const g = globalThis as unknown as { window: unknown; TOCK_ICON_DATA: Record<string, unknown> }
g.window = g
await import(resolve(from))
const out: Record<string, unknown> = {}
for (const name of tockNames) {
  if (!g.TOCK_ICON_DATA[name]) throw new Error(`no Tock icon "${name}"`)
  // Only the light weight renders here (duet lines); glass needs bold when its fill is "bold".
  const icon = g.TOCK_ICON_DATA[name] as { w: Record<string, string[]>; f: unknown }
  out[name] = { ...icon, w: { light: icon.w.light, ...(icon.f === "bold" ? { bold: icon.w.bold } : {}) } }
}
await writeFile(
  new URL("../vendor/tock-icons/data.js", import.meta.url),
  `/* eslint-disable */\n// Generated by scripts/tock-vendor.ts. Tock icons, forked from Phosphor Icons (MIT).\nwindow.TOCK_ICON_DATA = Object.assign(window.TOCK_ICON_DATA || {}, ${JSON.stringify(out)});\n`,
)
