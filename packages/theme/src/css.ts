import {
  COLOR_THEME_SHARED,
  COLOR_THEMES,
  DARK,
  DESKTOP,
  FONT,
  LIGHT,
  PREVIEW,
  PROPERTIES,
  SHELL,
  THEME,
  type ColorTheme,
  type Tokens,
} from "./tokens"
import { EFFECT_DARK, EFFECT_LIGHT } from "./effects"

export const DESKTOP_QUERY = "(width >= 768px), (hover: hover) and (pointer: fine)"

const lines = (table: Tokens) => Object.entries(table).map(([name, value]) => `--${name}: ${value};`)

const block = (selector: string, table: Tokens, indent = "") => {
  const body = lines(table)
  return body.length === 0 ? "" : `${indent}${selector} {\n${body.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`
}

const colorTheme = (attr: string, theme: ColorTheme) => [
  block(`${attr}:not(.dark)`, theme.light),
  block(`.dark${attr}`, theme.dark),
]

export function tokensCss(): string {
  return [
    "/* generated by packages/theme/scripts/gen-css.ts from src/tokens.ts */",
    ...PROPERTIES.map(
      (p) => `@property --${p.name} {\n  syntax: "${p.syntax}";\n  inherits: ${p.inherits};\n  initial-value: ${p.initial};\n}`,
    ),
    block("@theme static", THEME),
    block(":root", { ...FONT, ...SHELL, ...EFFECT_LIGHT }),
    block(":root, [data-theme-preview]", LIGHT),
    block(".dark", { ...DARK, ...EFFECT_DARK }),
    `@media ${DESKTOP_QUERY} {\n${block(":root", DESKTOP, "  ")}\n}`,
    ...colorTheme("[data-color-theme]", COLOR_THEME_SHARED),
    block("[data-theme-preview]", PREVIEW),
    ...Object.entries(COLOR_THEMES).flatMap(([name, theme]) => colorTheme(`[data-color-theme="${name}"]`, theme)),
    "",
  ]
    .filter((part, index, all) => part !== "" || index === all.length - 1)
    .join("\n\n")
}
